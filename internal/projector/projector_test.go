func TestLoadAndBuildPreserveLiteralProjectBody(t *testing.T) {
	root := t.TempDir()
	body := []byte("\r\n# Project\r\n\r\nKeep {{VERSION}}, ${name}, and <!-- GENERATED by awf: text --> literal.\r\n")
	writeTestFile(t, filepath.Join(root, ".awf", "project.md"), append([]byte("---\r\nunknown: ignored\r\nformat: 2\r\n---\r\n"), body...), 0o644)
	writeTestFile(t, filepath.Join(root, "docs", "topics", "z-last.md"), []byte("---\npaths: [docs/**]\nextra: ignored\n---\nopaque\n"), 0o644)
	writeTestFile(t, filepath.Join(root, "docs", "topics", "nested", "a-first.md"), []byte("---\npaths: [./internal//**/*.go]\n---\nBODY\r\n"), 0o644)
	writeTestFile(t, filepath.Join(root, ".awf", "topics", "ignored.md"), []byte("not a topic input\n"), 0o644)
	writeTestFile(t, filepath.Join(root, "docs", "ordinary.md"), []byte("not a topic input\n"), 0o644)

	sources, err := Load(root)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(sources.Project.Body, body) {
		t.Fatalf("project body = %q, want exact %q", sources.Project.Body, body)
	}
	if len(sources.Topics) != 2 {
		t.Fatalf("loaded %d topics, want only the two under docs/topics", len(sources.Topics))
	}
	if got := []string{sources.Topics[0].ID, sources.Topics[1].ID}; !slices.Equal(got, []string{"nested/a-first", "z-last"}) {
		t.Fatalf("topic IDs = %v", got)
	}
	if got := string(sources.Topics[0].Body); got != "BODY\r\n" {
		t.Fatalf("topic body = %q", got)
	}

	outputs := Build(sources)
	wantPaths := []string{
		".awf/.gitignore",
		".awf/bootstrap.sh",
		".claude/skills/awf-effort/SKILL.md",
		".claude/skills/awf-topics/SKILL.md",
		".pi/skills/awf-effort/SKILL.md",
		".pi/skills/awf-topics/SKILL.md",
		"AGENTS.md",
		"CLAUDE.md",
		"awf",
	}
	if got := outputPathsForTest(outputs); !slices.Equal(got, wantPaths) {
		t.Fatalf("output paths = %v, want %v", got, wantPaths)
	}
	agents := outputForTest(t, outputs, "AGENTS.md")
	if !bytes.HasSuffix(agents.Bytes, body) {
		t.Fatalf("AGENTS does not end with literal body:\n%s", agents.Bytes)
	}
	if bytes.Count(agents.Bytes, body) != 1 {
		t.Fatal("project body was transformed or inserted more than once")
	}
	if !bytes.HasPrefix(agents.Bytes, []byte(markdownMarker+"\n")) {
		t.Fatal("AGENTS marker is not first")
	}

	piTopic := outputForTest(t, outputs, ".pi/skills/awf-topics/SKILL.md")
	claudeTopic := outputForTest(t, outputs, ".claude/skills/awf-topics/SKILL.md")
	if !bytes.Equal(piTopic.Bytes, claudeTopic.Bytes) {
		t.Fatal("Pi and Claude topic skills differ")
	}
	if !bytes.Contains(piTopic.Bytes, []byte("\n---\n"+markdownMarker+"\n")) {
		t.Fatal("skill marker is not immediately after frontmatter")
	}
	if !bytes.Contains(piTopic.Bytes, []byte("docs topics")) {
		t.Error("topic skill does not route to the embedded guide")
	}
	piEffort := outputForTest(t, outputs, ".pi/skills/awf-effort/SKILL.md")
	claudeEffort := outputForTest(t, outputs, ".claude/skills/awf-effort/SKILL.md")
	if !bytes.Equal(piEffort.Bytes, claudeEffort.Bytes) {
		t.Fatal("Pi and Claude effort skills differ")
	}
	if !bytes.Contains(piEffort.Bytes, []byte("docs effort")) {
		t.Error("effort skill does not route to the embedded guide")
	}
	for _, relocated := range []string{"effort new <slug>", "git worktree add", "AWF does not manage Git"} {
		if bytes.Contains(piEffort.Bytes, []byte(relocated)) {
			t.Errorf("effort skill retained full-runbook phrase %q", relocated)
		}
	}
	for _, route := range []string{"./awf docs integration", "./awf docs topics", "./awf docs effort"} {
		if !bytes.Contains(agents.Bytes, []byte(route)) {
			t.Errorf("AGENTS missing direct documentation route %q", route)
		}
	}
	for _, path := range []string{"awf", ".awf/bootstrap.sh"} {
		output := outputForTest(t, outputs, path)
		lines := strings.Split(string(output.Bytes), "\n")
		if len(lines) < 2 || !strings.HasPrefix(lines[0], "#!") || lines[1] != textMarker {
			t.Errorf("%s marker is not after shebang", path)
		}
		if output.Mode.Perm()&0o111 == 0 {
			t.Errorf("%s is not executable", path)
		}
	}
	bootstrap := outputForTest(t, outputs, ".awf/bootstrap.sh")
	for _, phrase := range []string{`AWF_VERSION="${AWF_VERSION:-` + Version + `}"`, `releases/download/v${AWF_VERSION}`, "checksums.txt", "sha256sum -c -", "shasum -a 256 -c -"} {
		if !bytes.Contains(bootstrap.Bytes, []byte(phrase)) {
			t.Errorf("bootstrap missing %q", phrase)
		}
	}
	if bytes.Contains(bootstrap.Bytes, []byte("command -v awf")) {
		t.Fatal("bootstrap retained PATH probing")
	}

	launcher := PublicLauncher()
	for _, phrase := range []string{`AWF_VERSION="` + Version + `"`, `exec "$binary" "$@"`, "checksums.txt"} {
		if !bytes.Contains(launcher, []byte(phrase)) {
			t.Errorf("public launcher missing %q", phrase)
		}
	}
	if bytes.Contains(launcher, []byte(textMarker)) {
		t.Fatal("public launcher carries adopter generated-file ownership marker")
	}
	if bytes.Contains(launcher, []byte("releases/latest")) {
		t.Fatal("public launcher silently selects the latest binary release")
	}
	if bytes.Contains(launcher, []byte("${AWF_VERSION:-")) {
		t.Fatal("public launcher permits repository-style version override")
	}
}

func TestLoadRejectsInvalidSources(t *testing.T) {
	tests := []struct {
		name    string
		project string
		topic   string
	}{
		{name: "project frontmatter", project: "plain\n"},
		{name: "old project format", project: "---\nformat: 1\n---\nbody\n"},
		{name: "unknown project format", project: "---\nformat: 999\n---\nbody\n"},
		{name: "topic frontmatter", project: validProject("body\n"), topic: "plain\n"},
		{name: "topic paths", project: validProject("body\n"), topic: "---\npaths: []\n---\nbody\n"},
		{name: "topic escape", project: validProject("body\n"), topic: "---\npaths: [../**]\n---\nbody\n"},
		{name: "topic unsupported glob", project: validProject("body\n"), topic: "---\npaths: ['docs/[ab]']\n---\nbody\n"},
		{name: "global mixed with path", project: validProject("body\n"), topic: "---\npaths: ['**', 'src/**']\n---\nbody\n"},
		{name: "global duplicated", project: validProject("body\n"), topic: "---\npaths: ['**', '**']\n---\nbody\n"},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			root := t.TempDir()
			writeTestFile(t, filepath.Join(root, ".awf", "project.md"), []byte(test.project), 0o644)
			if test.topic != "" {
				writeTestFile(t, filepath.Join(root, "docs", "topics", "bad.md"), []byte(test.topic), 0o644)
			}
			if _, err := Load(root); err == nil {
				t.Fatal("Load accepted invalid source")
			}
		})
	}
}

func TestResolveGlobalsPathsAndEmptyResults(t *testing.T) {
	root := t.TempDir()
	writeTestFile(t, filepath.Join(root, ".awf", "project.md"), []byte(validProject("body\n")), 0o644)
	writeTopicForTest(t, root, "z-global.md", []string{"**"})
	writeTopicForTest(t, root, "a-go.md", []string{"src/**/*.go"})
	writeTopicForTest(t, root, "m-root.md", []string{"*", "docs/**"})
	writeTopicForTest(t, root, "n-normalized-double-star.md", []string{"./**"})

	matches, err := Resolve(root, nil)
	if err != nil {
		t.Fatal(err)
	}
	want := []TopicMatch{{ID: "z-global", SourcePath: "docs/topics/z-global.md"}}
	if !reflect.DeepEqual(matches, want) {
		t.Fatalf("empty Resolve = %#v, want %#v", matches, want)
	}

	matches, err = Resolve(root, []string{`src\new\future.go`, "unknown/file.txt", "src/new/future.go"})
	if err != nil {
		t.Fatal(err)
	}
	want = []TopicMatch{
		{ID: "a-go", SourcePath: "docs/topics/a-go.md"},
		{ID: "n-normalized-double-star", SourcePath: "docs/topics/n-normalized-double-star.md"},
		{ID: "z-global", SourcePath: "docs/topics/z-global.md"},
	}
	if !reflect.DeepEqual(matches, want) {
		t.Fatalf("path Resolve = %#v, want %#v", matches, want)
	}
	if _, err := os.Stat(filepath.Join(root, "src", "new", "future.go")); !errors.Is(err, fs.ErrNotExist) {
		t.Fatalf("resolve target unexpectedly exists: %v", err)
	}

	matches, err = Resolve(root, []string{"README.md"})
	if err != nil {
		t.Fatal(err)
	}
	want = []TopicMatch{
		{ID: "m-root", SourcePath: "docs/topics/m-root.md"},
		{ID: "n-normalized-double-star", SourcePath: "docs/topics/n-normalized-double-star.md"},
		{ID: "z-global", SourcePath: "docs/topics/z-global.md"},
	}
	if !reflect.DeepEqual(matches, want) {
		t.Fatalf("root Resolve = %#v, want %#v", matches, want)
	}

	writeTestFile(t, filepath.Join(root, "docs", "topics", "z-global.md"), []byte("---\npaths: [elsewhere/**]\n---\nbody\n"), 0o644)
	writeTestFile(t, filepath.Join(root, "docs", "topics", "n-normalized-double-star.md"), []byte("---\npaths: [elsewhere/**]\n---\nbody\n"), 0o644)
	matches, err = Resolve(root, []string{"nested/no-match"})
	if err != nil || len(matches) != 0 {
		t.Fatalf("no-match Resolve = %#v, %v", matches, err)
	}
}

